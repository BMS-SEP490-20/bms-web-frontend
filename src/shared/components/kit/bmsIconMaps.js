export function getCategoryIconKey(category) {
  if (!category) return 'general';
  const c = category.toLowerCase();
  if (c.includes('huyết') || c.includes('hemat')) return 'hematology';
  if (c.includes('sinh hóa') || c.includes('biochem')) return 'biochemistry';
  if (c.includes('miễn dịch') || c.includes('immun')) return 'immunology';
  if (c.includes('đông máu') || c.includes('coag')) return 'coagulation';
  if (c.includes('tiểu đường') || c.includes('đái tháo') || c.includes('diabet')) return 'diabetes';
  if (c.includes('gan') || c.includes('liver')) return 'liver';
  if (c.includes('tim') || c.includes('cardio') || c.includes('mỡ máu') || c.includes('lipid')) return 'cardio';
  if (c.includes('thận') || c.includes('kidney')) return 'kidney';
  if (c.includes('ung thư') || c.includes('oncol')) return 'oncology';
  if (c.includes('truyền nhiễm') || c.includes('infect')) return 'infectious';
  if (c.includes('mãn tính') || c.includes('chronic')) return 'chronic';
  if (c.includes('thai') || c.includes('matern')) return 'maternity';
  if (c.includes('nước tiểu') || c.includes('urinal')) return 'urinalysis';
  return 'general';
}
